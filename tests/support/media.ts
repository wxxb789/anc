/**
 * A deterministic progressive JPEG with several scans.
 *
 * A progressive file is the case the completeness walk must accept after an
 * entropy-coded segment: another `DHT`/`SOS` follows before `EOI`. Generated
 * rather than embedded so the fixture is demonstrably a real multi-scan JPEG
 * and not a hand-shaped byte sequence.
 */
export async function progressiveJpeg(): Promise<Uint8Array> {
  const width = 64;
  const height = 48;
  const raw = Buffer.alloc(width * height * 3);
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const index = (y * width + x) * 3;
      const u = x / (width - 1);
      const v = y / (height - 1);
      raw[index] = Math.round(255 * Math.min(1, 0.25 + 0.5 * u + 0.1 * Math.sin(v * 12)));
      raw[index + 1] = Math.round(255 * Math.min(1, 0.2 + 0.55 * v + 0.12 * Math.cos(u * 9)));
      raw[index + 2] = Math.round(255 * Math.min(1, 0.15 + 0.45 * ((u + v) / 2) + 0.1 * Math.sin((u + v) * 15)));
    }
  }
  return sharp(raw, { raw: { width, height, channels: 3 } })
    .jpeg({ quality: 88, progressive: true, chromaSubsampling: '4:2:0' })
    .toBuffer();
}

